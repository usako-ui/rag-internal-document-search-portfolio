-- ============================================================
-- user_settings から language 列を削除
--
-- 対応タスク：Q-40（2026-08-18 決定）
--
-- 【削除する理由】
-- UIの英語化（i18n）が未実装のため、「英語」を選んでも画面表示が変わらない。
-- 選んでも変化がない設定項目は利用者への誤案内になるため、
-- 日本語のみ対応として設定項目自体を削除する。
--
-- UIだけ消して列を残すと、どこからも読まれない列がスキーマに残り、
-- 納品資料や次の担当者にとって「使われているのか分からない」状態になるため、
-- 列も併せて削除する。
--
-- 【安全性について】
-- この列は 20260818120000_create_user_settings.sql で同日に追加したもので、
-- 参照しているコードは本コミットで全て削除済み。実データの欠損は発生しない。
--
-- 英語対応を行う場合は、全画面の文言・エラーメッセージ・日時書式を含む
-- 独立したタスクとして設計し直すこと（列の再追加もその時点で行う）。
-- ============================================================

-- CHECK制約は列の削除に伴って自動的に消えるため、個別のdropは不要
alter table public.user_settings
  drop column if exists language;
