/**
 * ナビゲーションの識別子
 *
 * サイドバー（PC・タブレット）とボトムナビ（スマホ）で同じIDを使い、
 * どのデバイスでも現在地の表示がずれないようにしている。
 *
 * 【2026-08-18 構成変更】
 * 「操作」単位だったナビ（PDFアップロード・資料更新・検索フィルター・文書一覧・
 * お気に入り）を「画面」単位へ統合した。同じ目的の操作が複数のナビへ散っていて、
 * 「どこから入ればよいか」が分かりにくかったため。
 *
 *   PDFアップロード + 資料更新        → documents（文書管理）
 *   検索フィルター + 文書一覧         → search（文書を検索）
 *   お気に入り                        → 廃止（MVPで実装していないため）
 */
export type NavId =
  | 'chat' // 新しい質問（チャット画面）
  | 'documents' // 文書管理（アップロード・更新）
  | 'search' // 文書を検索（フィルター・文書一覧）
  | 'history' // 質問履歴
  | 'dashboard' // ダッシュボード
  | 'settings'; // 設定
